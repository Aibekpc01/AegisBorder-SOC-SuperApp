export function BlockGuide({
  title,
  text,
  steps,
}: {
  title: string;
  text?: string;
  steps?: string;
}) {
  const page = useLocation().pathname.slice(1),
    navigate = useNavigate();
  const guide = guides[title] ||
    pageGuides[page] || {
      text: "Этот блок отображает данные системы.",
      steps:
        "Используйте доступные действия и проверьте результат уведомления.",
    };
  return (
    <div className="block-guide">
      <div className="block-guide-lead">
        <Info size={15} />
        <p>{text || guide.text}</p>
      </div>
      <details>
        <summary>
          Как пользоваться этим блоком <ChevronDown size={13} />
        </summary>
        <p>{steps || guide.steps}</p>
        {guide.path && (
          <Button variant="ghost" onClick={() => navigate(guide.path!)}>
            {guide.action}
            <ArrowUpRight size={14} />
          </Button>
        )}
      </details>
    </div>
  );
}
