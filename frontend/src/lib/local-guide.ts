import { explainers, glossary } from "./explainers";

export function localGuideAnswer(question: string, page: string): string {
  const query = question.trim().toLocaleLowerCase("ru").replace(/ё/g, "е");
  const guide =
    explainers[page] ||
    (page === "landing"
      ? {
          description: "Это знакомство с AegisBorder SuperApp — цифровым суперприложением для расследования киберинцидентов и защиты информации в Пограничной службе КНБ РК.",
          outcome:
            "Вы узнаете назначение проекта и сможете перейти к рабочей панели.",
          steps: [
            "Прочитайте описание и посмотрите обозначенный учебный пример.",
            "Откройте SuperApp и войдите с выданной учётной записью.",
            "Выберите пошаговую демонстрацию в рабочей панели.",
          ],
        }
      : undefined);
  if (!query) return "Напишите вопрос или выберите готовую подсказку ниже.";
  if (
    /(что дальше|как пользоваться|как работать|с чего начать|шаг|объясни страниц)/.test(
      query,
    ) &&
    guide
  ) {
    return `${guide.description}\n\n${guide.steps.map((step, i) => `${i + 1}. ${step}`).join("\n")}\n\nРезультат: ${guide.outcome}`;
  }
  if (/(\bai\b|(^|[^а-я])ии([^а-я]|$)|модел|бесплат|интернет)/.test(query))
    return "Этот помощник бесплатный и работает по встроенной инструкции. Языковая модель не подключена. Он объясняет страницы и блоки, показывает шаги и термины, но не придумывает ответы на произвольные вопросы и не выполняет действия за вас.";
  const aliases: Record<string, string> = {
    флешк: "Событие",
    джейсон: "JSON и CSV",
    пдф: "PDF",
  };
  const term =
    glossary.find((item) =>
      query.includes(item.term.toLocaleLowerCase("ru").replace(/ё/g, "е")),
    ) ||
    glossary.find((item) =>
      Object.entries(aliases).some(
        ([key, value]) => query.includes(key) && item.term === value,
      ),
    );
  if (term) return `${term.term}\n\n${term.text}`;
  if (
    /(весь сайт|вся система|что умеет|что это за|проект|экскурси)/.test(query)
  )
    return "AegisBorder — учебная система проверки подозрительных действий. Она сохраняет события, показывает предупреждения, помогает человеку проверить факты и подготовить отчёт.\n\nНачните с экскурсии: обзор → тренировка → подозрительные ситуации → документы → отчёты. Все примеры вымышленные. Помощник объясняет интерфейс по встроенным инструкциям; языковая модель не подключена.";
  if (/(пароль|войти|вход)/.test(query))
    return "Войдите с выданными вам именем пользователя и паролем. Если доступ потерян, обратитесь к администратору. Помощник не знает ваш пароль и не может изменить права доступа.";
  return `Я могу объяснять страницы, блоки и термины по встроенной инструкции. На этот вопрос у меня нет отдельного подготовленного ответа.\n\n${guide ? `На текущей странице: ${guide.description}\n\nНажмите «Покажи блоки», чтобы посмотреть её элементы по очереди.` : "Выберите «Экскурсия по сайту», чтобы начать знакомство."}`;
}

